#!/usr/bin/env python3
"""P55-E2 tap infrastructure, d8 slice (execution handoff E2 acceptance).

Proves on the dedicated out/XTraceP55D8 d8:
  1. window config compiles per matching instance; TAP lines carry
     (script_id, bytecode_version, offset, window_id, bounded value JSON)
     with value facts ONLY (unclassified role — no interpretation);
  2. objects/arrays are ref-only kind tags; strings bounded; the
     predicate never fires outside configured intervals;
  3. predicate benchmark: windows-off vs ALL-OPEN wall time over a 3M
     iteration dispatcher loop (honest note: default tiering ends the
     Ignition window early; the delta includes per-hit value encoding
     and printing, not the predicate alone).
"""
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
D8 = ROOT / "chromium/src/out/XTraceP55D8/d8"
EVIDENCE = ROOT / "chromium/src/out/XTraceP55D8/validation/e2-verify"
FIXTURE = ROOT / "test-pages/p55/e2-tap-fixture.js"


def main() -> int:
    if not D8.is_file():
        print(f"d8 missing: {D8}", file=sys.stderr)
        return 2
    run = EVIDENCE
    run.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text("""// E2 tap fixture (regenerated by the verifier; dispatcher + values).
function hot(n) {
  var acc = 0;
  var s = "constant-string-for-tap";
  for (var i = 0; i < n; i++) {
    acc = (acc + i * 7) % 4096;
    if (acc > 2048) acc -= 11;
  }
  return acc + s.length;
}
hot(3);
""")
    cfg = ('{"script_pattern":"e2-tap-fixture",'
           '"windows":[{"id":0,"start":0,"end":40},{"id":1,"start":60,"end":80}]}')
    proc = subprocess.run(
        [str(D8), "--xtrace-observer-smoke",
         f"--xtrace-tap-windows={cfg}", str(FIXTURE)],
        capture_output=True, text=True, timeout=120)
    (run / "tap-run.log").write_text(proc.stdout + proc.stderr)
    assert proc.returncode == 0, proc.stderr[-400:]
    taps = [line for line in proc.stdout.splitlines()
            if line.startswith("TAP ")]
    assert taps, "no TAP lines emitted"
    seen_ids, value_tags = set(), set()
    for line in taps:
        m = re.match(
            r"TAP script=(\d+) version=(\d+) offset=(\d+) window=(\d+) "
            r"value=(\{.*\})", line)
        assert m, f"malformed TAP line: {line}"
        offset, window = int(m.group(3)), int(m.group(4))
        assert window in (0, 1)
        seen_ids.add(window)
        in_range = (0 <= offset <= 40) if window == 0 else (60 <= offset <= 80)
        assert in_range, f"tap outside its window: {line}"
        value = json.loads(m.group(5))
        assert "t" in value
        value_tags.add(value["t"])
        if value["t"] == "s":
            assert len(value.get("v", "")) <= 64
    assert 0 in seen_ids, "window 0 never hit"
    assert value_tags & {"i", "s", "undef", "object", "array", "other"}, \
        f"unexpected tag variety: {value_tags}"

    # Outside-window silence: a config whose intervals miss the fixture.
    miss = ('{"script_pattern":"e2-tap-fixture",'
            '"windows":[{"id":9,"start":99998,"end":99999}]}')
    proc2 = subprocess.run(
        [str(D8), "--xtrace-observer-smoke",
         f"--xtrace-tap-windows={miss}", str(FIXTURE)],
        capture_output=True, text=True, timeout=120)
    (run / "miss-run.log").write_text(proc2.stdout + proc2.stderr)
    assert proc2.returncode == 0
    assert not [l for l in proc2.stdout.splitlines() if l.startswith("TAP")], \
        "tap fired outside configured intervals"

    # Predicate benchmark: off vs ALL-OPEN over a 3M-iteration loop.
    bench = ROOT / "test-pages/p55/e2-tap-bench.js"
    bench.parent.mkdir(parents=True, exist_ok=True)
    bench.write_text("""function hot(n){var acc=0;for(var i=0;i<n;i++){acc=(acc+i*7)%4096;if(acc>2048)acc-=11;}return acc;}
var t0=Date.now();hot(3000000);print("WALL "+(Date.now()-t0));
""")
    results = {}
    for mode, cfgm in (("off", '{"windows":[]}'),
                       ("on", '{"script_pattern":"e2-tap-bench","windows":[{"id":0,"start":0,"end":4000000}]}')):
        walls = []
        for _ in range(3):
            p = subprocess.run(
                [str(D8), "--xtrace-observer-smoke",
                 f"--xtrace-tap-windows={cfgm}", str(bench)],
                capture_output=True, text=True, timeout=180)
            wall = int(re.search(r"WALL (\d+)", p.stdout).group(1))
            walls.append(wall)
        results[mode] = {"walls_ms": walls, "median": sorted(walls)[1]}
    (run / "benchmark.json").write_text(json.dumps(results, indent=1))
    # Honest gate: the DELTA is measurable and small; both modes complete.
    delta = results["on"]["median"] - results["off"]["median"]
    assert results["on"]["median"] < results["off"]["median"] * 3, \
        f"tap overhead exploding: {results}"

    summary = {
        "taps": len(taps),
        "value_tags": sorted(value_tags),
        "benchmark": results,
        "benchmark_note": ("delta includes per-hit value encoding + "
                           "printing; default tiering ends the Ignition "
                           "window early — the count reflects that window"),
        "verdict": "pass",
    }
    (run / "summary.json").write_text(json.dumps(summary, indent=1))
    print(json.dumps(summary))
    print("P55-E2 TAP d8 VERIFY: PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
