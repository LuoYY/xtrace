// P4-E6: P0 sample parity — the ten P0 bytecode cases run in d8 with the
// structured observer open AND the upstream trace on; the observer's event
// count per case must match the upstream Entry count (offset-normalized,
// one logical Entry per instruction), and semantics must be unchanged.
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const fs = require('node:fs'); const path = require('node:path');
const d8 = require('node:path').resolve(__dirname, '../chromium/src/out/XTraceP4D8/d8');
const outDir = path.join(path.dirname(d8), 'validation', 'p4-e6-parity');
fs.mkdirSync(outDir, { recursive: true });

const cases = {
  'short-star': ['function xt_case(x) { let y = x + 1; return y * 2; }', 'xt_case(4)', 10],
  'wide': ['function xt_case() { return 256; }', 'xt_case()', 256],
  'extra-wide': ['function xt_case() { return 65536; }', 'xt_case()', 65536],
  'branch-loop': ['function xt_case(n) { let s = 0; for (let i = 0; i < n; i++) { if (i & 1) s += i; else s -= i; } return s; }', 'xt_case(5)', -2],
  'recursive-call': ['function xt_case(n) { if (n <= 1) return 1; return n * xt_case(n - 1); }', 'xt_case(5)', 120],
  'throw-catch': ['function xt_case() { try { throw 7; } catch (e) { return e + 1; } }', 'xt_case()', 8],
  'rethrow-finally': ['function xt_case() { try { throw 9; } finally { globalThis.cleanup = 1; } } function run() { try { xt_case(); } catch (e) { return [e, cleanup]; } }', 'run()', [9, 1]],
  'generator': ['function* xt_case() { yield 3; return 5; } function run() { let g = xt_case(); return [g.next(), g.next()]; }', 'run()', [{'value': 3, 'done': false}, {'value': 5, 'done': true}]],
  'async-await': ['async function xt_case() { return (await Promise.resolve(4)) + 2; } function run() { return xt_case(); }', 'run()', 6],
  'wide-register': ['function xt_case(x) { ' + Array.from({length: 270}, (_, i) => `let v${i} = x + ${i};`).join(' ') + ' return [' + Array.from({length: 270}, (_, i) => `v${i}`).join(',') + '].length; }', 'xt_case(1)', 270],
};

const header = /generated bytecode for function: xt_case|generated bytecode for function: setup/;
const entry = /^\s*(B->|->)\s*(0x[0-9a-f]+)\s+@\s*(\d+)\s*:/;

function upstreamEntries(stdout) {
  // Count upstream Entry lines while INSIDE a target function's bytecode
  // dump region is fragile in string form; instead count "-> @offset :"
  // lines attributed to the last printed function header. Simpler robust
  // metric: total dynamic Entry lines for the whole run is polluted by
  // d8 internals. We scope by collecting entries AFTER the LAST
  // "[generated bytecode for function: <name>]" header.
  const lines = stdout.split('\n');
  let count = 0; let inTarget = false;
  for (const line of lines) {
    if (/generated bytecode for function/.test(line)) {
      inTarget = /xt_case|setup/.test(line);
      continue;
    }
    if (inTarget && entry.test(line)) count++;
  }
  return count;
}

const results = [];
for (const [name, [source, expression, expected]] of Object.entries(cases)) {
  // Single run with BOTH the structured observer and the upstream trace:
  // both instruments count every interpreted bytecode execution in the
  // process, so process-wide totals must match exactly.
  const awaited = name === 'async-await';
  const run = spawnSync(d8, ['--max-opt=0', '--trace-ignition',
    '--xtrace-observer-smoke', '-e',
    awaited
      ? source + '\n' + expression + '.then(v => print("XTRES=" + JSON.stringify(v)))'
      : source + '\nprint("XTRES=" + JSON.stringify(' + expression + '))'],
    { encoding: 'utf8', timeout: 60000 });
  const obsCount = Number((run.stdout.match(/observer events=(\d+)/) || [])[1] || 0);
  const cleanOut = run.stdout
    .replace(/\u001b\[[0-9;]*m/g, '')
    .replace(/^OBS script=.*$/gm, '');
  const obsResult = (cleanOut.match(/^XTRES=(.*)$/m) || [])[1];
  const clean = run.stdout.replace(/\u001b\[[0-9;]*m/g, '');
  const upTotal = (clean.match(/^\s*(?:B->|->)\s*0x/gm) || []).length;

  const row = { name, obsCount, upTotal, equal: obsCount === upTotal };
  results.push(row);
  console.log(JSON.stringify(row));
  assert(obsCount > 0, `${name}: observer saw nothing`);
  assert(upTotal > 0, `${name}: upstream trace saw nothing`);
  assert(obsCount === upTotal,
      `${name}: observer ${obsCount} != upstream ${upTotal}`);
  const parsed = JSON.parse(obsResult);
  assert.deepStrictEqual(parsed, expected,
      `${name}: expected ${JSON.stringify(expected)}, got ${obsResult}`);
}
fs.writeFileSync(path.join(outDir, 'summary.json'), JSON.stringify(results, null, 2));
console.log(`PASS: 10-case observer/upstream parity + semantics`);
console.log(`Evidence: ${outDir}`);
